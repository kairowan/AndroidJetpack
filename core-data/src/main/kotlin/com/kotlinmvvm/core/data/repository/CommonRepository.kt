interface CommonRepository<in Params : Any, out Result : Any> {
    /**
     * 根据 [params] 加载一份稳定的业务结果。
     *
     * 实现可以读取缓存或请求远程数据；预期失败应包含在结果类型中，不得泄漏传输层异常。
     */
    suspend fun load(params: Params): Result
}
