sealed interface NetworkFailure {
    /** 供日志、指标和告警聚合使用的稳定代码，不依赖可被混淆的类型名称。 */
    val diagnosticCode: String

    /** 当前错误是否适合由上层在用户触发或退避策略下重试。 */
    val retryable: Boolean
}
